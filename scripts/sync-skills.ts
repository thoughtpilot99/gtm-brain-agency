/**
 * Skills live once in skills/<name>/SKILL.md. This copies them into the folders each agent reads:
 * .claude/skills (Claude Code, also read by Grok Build) and .agents/skills (Codex).
 * Copies instead of symlinks so it works on Windows without admin rights.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ROOT } from "../packages/core/src/env";

export function syncSkills(): string[] {
  const src = path.join(ROOT, "skills");
  if (!fs.existsSync(src)) return [];
  const names = fs.readdirSync(src, { withFileTypes: true }).filter((d) => d.isDirectory() && fs.existsSync(path.join(src, d.name, "SKILL.md"))).map((d) => d.name);
  for (const target of [".claude/skills", ".agents/skills"]) {
    const dir = path.join(ROOT, target);
    fs.mkdirSync(dir, { recursive: true });
    for (const existing of fs.readdirSync(dir)) {
      const marker = path.join(dir, existing, ".synced");
      if (fs.existsSync(marker) && !names.includes(existing)) fs.rmSync(path.join(dir, existing), { recursive: true, force: true });
    }
    for (const n of names) {
      const to = path.join(dir, n);
      fs.rmSync(to, { recursive: true, force: true });
      fs.cpSync(path.join(src, n), to, { recursive: true });
      fs.writeFileSync(path.join(to, ".synced"), "Generated by npm run sync-skills. Edit skills/ instead.\n");
    }
  }
  return names;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`Synced: ${syncSkills().join(", ")}`);
}
